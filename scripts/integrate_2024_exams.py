start_id = len(existing_qs) + 1
newly_added = []

for q_item in NEW_2024_QUESTIONS:
    q_words = set(re.findall(r'\w+', q_item['question']))
    is_dup = False
    for eq in existing_qs:
        eq_words = set(re.findall(r'\w+', eq['question']))
        overlap = len(q_words.intersection(eq_words))
        if overlap > len(q_words) * 0.75:
            is_dup = True
            break
            
    if not is_dup:
        q_item['id'] = f"q_{start_id:03d}"
        q_item['explanation'] = f"נימוק פדגוגי מורחב: {q_item['aiExplanation']}"
        newly_added.append(q_item)
        start_id += 1

print(f"Total unique 2024 questions added: {len(newly_added)}")

combined_qs = existing_qs + newly_added


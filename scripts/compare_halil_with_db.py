print(f"Checking {len(halil_questions)} questions against {len(db)} DB questions...")
matches = []
for idx, q_text in enumerate(halil_questions, 1):
    q_words = normalize(q_text)
    best_score = 0
    best_match = None
    for db_q in db:
        db_words = normalize(db_q['question'])
        common = q_words.intersection(db_words)
        score = len(common) / len(q_words) if q_words else 0
        if score > best_score:
            best_score = score
            best_match = db_q
    if best_score >= 0.5:
        matches.append((idx, best_score, best_match))

print(f"Found {len(matches)} potential overlaps (score >= 0.5):")
for idx, score, m in matches[:30]:
    print(f"Halil #{idx} -> Score {score:.2f} with {m['id']} ({m.get('source')}): {m['question'][:50]}")

with open('halil_matches.json', 'w', encoding='utf-8') as f:
    json.dump([{'halil_idx': idx, 'score': score, 'db_id': m['id'], 'db_source': m.get('source'), 'db_q': m['question']} for idx, score, m in matches], f, ensure_ascii=False, indent=2)
